import { createHash } from "node:crypto";
import {
  copyFileSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { basename, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

export const updatePlatforms = {
  "windows-x86_64": "x64-setup.exe",
  "darwin-aarch64": "aarch64.app.tar.gz",
  "darwin-x86_64": "x86_64.app.tar.gz",
};

export function updaterBuildConfig(enabled, env, mac, unsigned) {
  if (!enabled) return { bundle: { createUpdaterArtifacts: false } };
  if (mac && unsigned)
    throw new Error("macOS updater releases require Developer ID signing");
  if (unsigned)
    throw new Error(
      "--unsigned/--no-sign also skips updater signatures; remove it when using --updater",
    );
  if (!env.TAURI_SIGNING_PRIVATE_KEY?.trim())
    throw new Error("TAURI_SIGNING_PRIVATE_KEY is required for --updater");
  const key = env.CLYNTIS_UPDATER_PUBLIC_KEY?.trim() ?? "";
  const decoded = Buffer.from(key, "base64").toString("utf8");
  const payload = decoded.trim().split(/\r?\n/).at(-1) ?? "";
  const publicKey = Buffer.from(payload, "base64");
  if (
    !/^[A-Za-z0-9+/]+={0,2}$/.test(key) ||
    publicKey.length !== 42 ||
    publicKey.subarray(0, 2).toString() !== "Ed"
  )
    throw new Error(
      "CLYNTIS_UPDATER_PUBLIC_KEY must contain the base64 public key generated by tauri signer",
    );
  if (env.CLYNTIS_UPDATER_ENDPOINT) {
    const url = new URL(env.CLYNTIS_UPDATER_ENDPOINT);
    if (url.protocol !== "https:" || url.username || url.password)
      throw new Error(
        "CLYNTIS_UPDATER_ENDPOINT must be an HTTPS URL without credentials",
      );
  }
  return {
    bundle: { createUpdaterArtifacts: true },
    plugins: { updater: { pubkey: key } },
  };
}

function versionCheck(version) {
  if (!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version))
    throw new Error(
      "Updater releases require a stable major.minor.patch version",
    );
}
export function updateFilename(platform, version) {
  versionCheck(version);
  const suffix = updatePlatforms[platform];
  if (!suffix) throw new Error(`Unsupported updater platform: ${platform}`);
  return `Clyntis_${version}_${suffix}`;
}
function filesIn(directory) {
  return readdirSync(directory).flatMap((name) => {
    const path = join(directory, name);
    return statSync(path).isDirectory() ? filesIn(path) : [path];
  });
}
export function validateSignatureMetadata(signature, version) {
  const decoded = Buffer.from(signature, "base64").toString("utf8");
  const comment = decoded
    .split(/\r?\n/)
    .find((line) => line.startsWith("trusted comment: "));
  const signedVersion = comment
    ?.slice("trusted comment: ".length)
    .split("\t")
    .find((field) => field.startsWith("version:"))
    ?.slice("version:".length);
  if (!/^[A-Za-z0-9+/]+={0,2}$/.test(signature) || signedVersion !== version)
    throw new Error(
      `Missing or mismatched signature version: expected ${version}`,
    );
}
export function findUpdaterArtifact(bundle, platform, version) {
  updateFilename(platform, version);
  const files = filesIn(bundle);
  const candidates = files.filter((path) =>
    platform === "windows-x86_64"
      ? path.endsWith("-setup.exe")
      : path.endsWith(".app.tar.gz"),
  );
  if (candidates.length !== 1)
    throw new Error(
      `Expected one updater artifact for ${platform}, got ${candidates.length}`,
    );
  const source = candidates[0];
  const signature = readFileSync(`${source}.sig`, "utf8").trim();
  if (!signature) throw new Error(`Missing updater signature: ${source}`);
  validateSignatureMetadata(signature, version);
  return { source, signature, files };
}
export function collectUpdates(bundle, output, platform, version) {
  const { source, signature, files } = findUpdaterArtifact(
    bundle,
    platform,
    version,
  );
  const name = updateFilename(platform, version);
  mkdirSync(output, { recursive: true });
  copyFileSync(source, join(output, name));
  writeFileSync(join(output, `${name}.sig`), signature + "\n");
  const hash = createHash("sha256").update(readFileSync(source)).digest("hex");
  writeFileSync(join(output, `${name}.sha256`), `${hash}  ${name}\n`);
  for (const dmg of files.filter((file) => file.endsWith(".dmg")))
    copyFileSync(dmg, join(output, basename(dmg)));
}

export function createManifest(
  directory,
  version,
  repository,
  notes = "",
  now = new Date(),
) {
  versionCheck(version);
  if (!/^[\w.-]+\/[\w.-]+$/.test(repository))
    throw new Error("Invalid GitHub repository");
  const platforms = {};
  for (const platform of Object.keys(updatePlatforms)) {
    const name = updateFilename(platform, version);
    if (statSync(join(directory, name)).size === 0)
      throw new Error(`Empty updater artifact: ${name}`);
    const signature = readFileSync(
      join(directory, `${name}.sig`),
      "utf8",
    ).trim();
    if (!signature) throw new Error(`Empty updater signature: ${name}`);
    validateSignatureMetadata(signature, version);
    platforms[platform] = {
      signature,
      url: `https://github.com/${repository}/releases/download/v${version}/${encodeURIComponent(name)}`,
    };
  }
  return { version, notes, pub_date: now.toISOString(), platforms };
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  const [command, directory, output, version, platformOrRepo, notesPath] =
    process.argv.slice(2);
  if (command === "collect")
    collectUpdates(directory, output, platformOrRepo, version);
  else if (command === "manifest")
    writeFileSync(
      output,
      JSON.stringify(
        createManifest(
          directory,
          version,
          platformOrRepo,
          notesPath ? readFileSync(notesPath, "utf8") : "",
        ),
        null,
        2,
      ) + "\n",
    );
  else
    throw new Error(
      "Usage: updates.mjs collect <bundle> <output> <version> <platform> | manifest <assets> <output.json> <version> <owner/repo> [notes.txt]",
    );
}
